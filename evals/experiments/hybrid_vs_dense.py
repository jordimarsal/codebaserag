from pathlib import Path

from coderag.config import Settings
from coderag.ingest.pipeline import collect_chunks
from coderag.retrieval.bm25 import InMemoryBm25
from coderag.retrieval.reranker import CrossEncoderReranker
from coderag.retrieval.retriever import Retriever
from coderag.stores.memory import InMemoryVectorStore
from evals.dataset import load_golden
from evals.embedder import HashEmbedder
from evals.harness import experiment_markdown, run_retrieval_eval

GOLDEN = Path(__file__).resolve().parents[1] / "golden"
RESULTS = Path(__file__).resolve().parent / "hybrid_vs_dense.md"
STRATEGIES = ["dense", "hybrid", "hybrid+rerank"]


def _build_retriever(settings: Settings, strategy: str) -> Retriever:
    chunks = collect_chunks(Path(settings.repo), chunk_size=settings.chunk_size)
    embedder = HashEmbedder()
    store = InMemoryVectorStore(dim=embedder.dim())
    store.upsert(chunks, embedder.embed([chunk.text for chunk in chunks]))
    bm25 = InMemoryBm25()
    bm25.index(chunks)
    reranker = CrossEncoderReranker(settings.rerank_model) if "rerank" in strategy else None
    return Retriever(
        store,
        bm25,
        embedder,
        reranker=reranker,
        strategy=strategy,
        top_k=5,
        rerank_top_n=settings.rerank_top_n,
    )


def run_experiment() -> str:
    entries = load_golden(GOLDEN)
    settings = Settings()
    reports = {
        strategy: run_retrieval_eval(
            entries, _build_retriever(settings, strategy).retrieve, top_k=5
        )
        for strategy in STRATEGIES
    }
    return experiment_markdown(reports)


def main() -> None:
    table = run_experiment()
    narrative = (
        "# Experiment: hybrid vs dense retrieval\n\n"
        "Generated by `evals/experiments/hybrid_vs_dense`. Side-by-side retrieval quality "
        "per strategy on the golden dataset (`evals/golden/codebaserag.yaml`); uses the "
        "offline `HashEmbedder` + `InMemoryBm25` so it runs without services.\n\n"
        "## Results\n\n"
    )
    RESULTS.write_text(narrative + table + "\n", encoding="utf-8")
    print(table)


if __name__ == "__main__":  # pragma: no cover
    main()
